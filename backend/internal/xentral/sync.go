// Engine executes bidirectional sync between Xentral and LastSaaS.
//
// Inbound (Xentral → LastSaaS): products, customers, suppliers, purchase orders, sales orders.
// Outbound (LastSaaS → Xentral): product EAN, product freefields.
// SPoT rules:
//   - lastEk (purchase price): LastSaaS is authoritative; Xentral value only used on first import.
//   - ean: LastSaaS is authoritative if already set (e.g. generated by EANRange).
//
// The XentralMapping collection is used as a join table so that repeated
// syncs update existing records rather than inserting duplicates.
type Engine struct {
	db *db.MongoDB
}

func NewEngine(database *db.MongoDB) *Engine {
	return &Engine{db: database}
}

// -------------------------------------------------------------------
// Products (Xentral articles → LastSaaS products)
// -------------------------------------------------------------------

func (e *Engine) SyncProducts(ctx context.Context, tenantID primitive.ObjectID, client *Client) models.XentralSyncLog {
	log := e.startLog(ctx, tenantID, "products")

	articles, err := client.ListArticles(ctx)
	if err != nil {
		return e.failLog(ctx, log, err.Error())
	}

	for _, a := range articles {
		if err := e.upsertProduct(ctx, tenantID, a); err != nil {
			log.Errors = append(log.Errors, fmt.Sprintf("%s: %v", a.ID, err))
			log.Skipped++
		} else {
			// distinguish create vs update via mapping existence check (already done in upsertProduct)
			log.Updated++
		}
	}

	return e.finishLog(ctx, log)
}

func (e *Engine) upsertProduct(ctx context.Context, tenantID primitive.ObjectID, a XArticle) error {
	if a.ID == "" || a.Name == "" {
		return nil // skip incomplete records
	}

	// Look up existing mapping
	var mapping models.XentralMapping
	err := e.db.XentralMappings().FindOne(ctx, bson.M{
		"tenantId":  tenantID,
		"entity":    "product",
		"xentralId": a.ID,
	}).Decode(&mapping)

	now := time.Now()
	articleNr := a.ResolvedArticleNumber()
	nameShort := truncate(a.Name, 45)
	if nameShort == "" {
		nameShort = truncate(articleNr, 45)
	}

	tags := resolveTagNames(a.Tags)
	attrs := resolveAttributes(a.ResolvedCharacteristics())
	active := !a.IsDisabled || a.Active

	freeFields := resolveFreeFields(a.FreeFields)

	if err == mongo.ErrNoDocuments {
		// Create new product
		product := models.Product{
			ID:          primitive.NewObjectID(),
			TenantID:    tenantID,
			NameShort:   nameShort,
			NameLong:    truncate(a.Name, 255),
			Description: a.Description,
			EAN:         truncate(a.EAN, 32),
			WeightKg:    a.ResolvedWeight(),
			LastEK:      a.ResolvedPurchasePrice(),
			LastVK:      a.ResolvedSellPrice(),
			Tags:        tags,
			Attributes:  attrs,
			XentralNr:   truncate(articleNr, 50),
			Active:      active,
			FreeFields:  freeFields,
			CreatedAt:   now,
			UpdatedAt:   now,
		}
		if _, err := e.db.Products().InsertOne(ctx, product); err != nil {
			return fmt.Errorf("insert product: %w", err)
		}
		_, _ = e.db.XentralMappings().InsertOne(ctx, models.XentralMapping{
			ID:        primitive.NewObjectID(),
			TenantID:  tenantID,
			Entity:    "product",
			LocalID:   product.ID,
			XentralID: a.ID,
			XentralNr: articleNr,
			CreatedAt: now,
			UpdatedAt: now,
		})
		return nil
	}
	if err != nil {
		return fmt.Errorf("lookup mapping: %w", err)
	}

	// Update existing product.
	// lastEk is our SPoT: never overwrite a price we've set ourselves.
	// ean is also ours: if a local EAN is already set (e.g. generated by our EANRange),
	// do not overwrite it with whatever Xentral has.
	// name, description, tags, attributes, active, xentralNr all reflect Xentral (SPoT).
	setFields := bson.M{
		"nameShort":   nameShort,
		"nameLong":    truncate(a.Name, 255),
		"description": a.Description,
		"weightKg":    a.ResolvedWeight(),
		"tags":        tags,
		"attributes":  attrs,
		"xentralNr":   truncate(articleNr, 50),
		"active":      active,
		"freeFields":  freeFields,
		"updatedAt":   now,
	}

	// Fetch current product to check whether EAN / lastEk / lastVk are already set
	var existing struct {
		EAN    string  `bson:"ean"`
		LastEK float64 `bson:"lastEk"`
		LastVK float64 `bson:"lastVk"`
	}
	_ = e.db.Products().FindOne(ctx, bson.M{"_id": mapping.LocalID}).Decode(&existing)

	purchasePrice := a.ResolvedPurchasePrice()
	sellPrice := a.ResolvedSellPrice()
	if existing.EAN == "" && a.EAN != "" {
		setFields["ean"] = truncate(a.EAN, 32)
	}
	if existing.LastEK == 0 && purchasePrice > 0 {
		setFields["lastEk"] = purchasePrice
	}
	if existing.LastVK == 0 && sellPrice > 0 {
		setFields["lastVk"] = sellPrice
	}

	_, _ = e.db.Products().UpdateOne(ctx,
		bson.M{"_id": mapping.LocalID, "tenantId": tenantID},
		bson.M{"$set": setFields},
	)
	_, _ = e.db.XentralMappings().UpdateOne(ctx,
		bson.M{"_id": mapping.ID},
		bson.M{"$set": bson.M{"xentralNr": articleNr, "updatedAt": now}},
	)
	return nil
}

// -------------------------------------------------------------------
// Customers (Xentral customers → LastSaaS customers)
// -------------------------------------------------------------------

func (e *Engine) SyncCustomers(ctx context.Context, tenantID primitive.ObjectID, client *Client) models.XentralSyncLog {
	log := e.startLog(ctx, tenantID, "customers")

	customers, err := client.ListCustomers(ctx)
	if err != nil {
		return e.failLog(ctx, log, err.Error())
	}

	for _, c := range customers {
		if err := e.upsertCustomer(ctx, tenantID, c); err != nil {
			log.Errors = append(log.Errors, fmt.Sprintf("%s: %v", c.ID, err))
			log.Skipped++
		} else {
			log.Updated++
		}
	}

	return e.finishLog(ctx, log)
}

func (e *Engine) upsertCustomer(ctx context.Context, tenantID primitive.ObjectID, xc XCustomer) error {
	if xc.ID == "" {
		return nil
	}
	company := xc.ResolvedCompany()
	if company == "" {
		return fmt.Errorf("no company/name in response")
	}

	var mapping models.XentralMapping
	err := e.db.XentralMappings().FindOne(ctx, bson.M{
		"tenantId":  tenantID,
		"entity":    "customer",
		"xentralId": xc.ID,
	}).Decode(&mapping)

	now := time.Now()
	ra := xc.ResolvedAddress()
	addr := models.CustomerAddress{
		Street:  ra.Street,
		City:    ra.City,
		Zip:     ra.ResolvedZip(),
		Country: ra.Country,
	}

	if err == mongo.ErrNoDocuments {
		customer := models.Customer{
			ID:        primitive.NewObjectID(),
			TenantID:  tenantID,
			Company:   truncate(company, 200),
			Firstname: truncate(xc.FirstName, 50),
			Lastname:  truncate(xc.LastName, 50),
			Email:     truncate(xc.Email, 120),
			Phone:     truncate(xc.Phone, 50),
			Address:   addr,
			CreatedAt: now,
			UpdatedAt: now,
		}
		if _, err := e.db.Customers().InsertOne(ctx, customer); err != nil {
			return fmt.Errorf("insert customer: %w", err)
		}
		_, _ = e.db.XentralMappings().InsertOne(ctx, models.XentralMapping{
			ID:        primitive.NewObjectID(),
			TenantID:  tenantID,
			Entity:    "customer",
			LocalID:   customer.ID,
			XentralID: xc.ID,
			XentralNr: xc.CustomerNumber,
			CreatedAt: now,
			UpdatedAt: now,
		})
		return nil
	}
	if err != nil {
		return fmt.Errorf("lookup mapping: %w", err)
	}

	_, _ = e.db.Customers().UpdateOne(ctx,
		bson.M{"_id": mapping.LocalID, "tenantId": tenantID},
		bson.M{"$set": bson.M{
			"company":   truncate(company, 200),
			"firstname": truncate(xc.FirstName, 50),
			"lastname":  truncate(xc.LastName, 50),
			"email":     truncate(xc.Email, 120),
			"phone":     truncate(xc.Phone, 50),
			"address":   addr,
			"updatedAt": now,
		}},
	)
	return nil
}

