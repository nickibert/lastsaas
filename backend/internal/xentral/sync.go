func (e *Engine) upsertSalesOrder(ctx context.Context, tenantID primitive.ObjectID, xo XSalesOrder) error {
	if xo.ID == "" {
		return nil
	}

	var mapping models.XentralMapping
	err := e.db.XentralMappings().FindOne(ctx, bson.M{
		"tenantId":  tenantID,
		"entity":    "sales_order",
		"xentralId": xo.ID,
	}).Decode(&mapping)

	now := time.Now()

	orderDate := now
	if xo.Date != "" {
		if t, parseErr := time.Parse("2006-01-02", xo.Date); parseErr == nil {
			orderDate = t
		}
	}

	customerID := e.resolveCustomerID(ctx, tenantID, xo.Customer.ID)

	var lineItems []models.SalesOrderLineItem
	for _, item := range xo.LineItems {
		li := models.SalesOrderLineItem{
			XentralArticleID: item.Article.ID,
			Description:      item.Description,
			Quantity:         item.Quantity,
			UnitPriceEUR:     item.UnitPrice,
			TotalPriceEUR:    item.UnitPrice * item.Quantity,
		}
		if pid := e.resolveProductID(ctx, tenantID, item.Article.ID); pid != nil {
			li.ProductID = pid
		}
		lineItems = append(lineItems, li)
	}

	netSales := xo.NetSales.Float64()
	total := xo.Total.Float64()
	currency := xo.Currency
	if currency == "" {
		currency = xo.NetSales.Currency
	}
	soUserDefs := mapFreifelderToUserDefs(xo.ResolvedFreifelder())

	if err == mongo.ErrNoDocuments {
		so := models.SalesOrder{
			ID:                primitive.NewObjectID(),
			TenantID:          tenantID,
			CustomerID:        customerID,
			XentralDocumentNr: xo.DocumentNumber,
			ExternalOrderNr:   xo.ExternalOrderNumber,
			Date:              orderDate,
			Status:            xo.Status,
			LineItems:         lineItems,
			TotalNetEUR:       netSales,
			TotalGrossEUR:     total,
			Currency:          currency,
			UserDef01:         soUserDefs[0],
			UserDef02:         soUserDefs[1],
			UserDef03:         soUserDefs[2],
			UserDef04:         soUserDefs[3],
			UserDef05:         soUserDefs[4],
			UserDef06:         soUserDefs[5],
			UserDef07:         soUserDefs[6],
			UserDef08:         soUserDefs[7],
			UserDef09:         soUserDefs[8],
			UserDef10:         soUserDefs[9],
			CreatedAt:         now,
			UpdatedAt:         now,
		}
		if _, insertErr := e.db.SalesOrders().InsertOne(ctx, so); insertErr != nil {
			return fmt.Errorf("insert sales order: %w", insertErr)
		}
		_, _ = e.db.XentralMappings().InsertOne(ctx, models.XentralMapping{
			ID:        primitive.NewObjectID(),
			TenantID:  tenantID,
			Entity:    "sales_order",
			LocalID:   so.ID,
			XentralID: xo.ID,
			XentralNr: xo.DocumentNumber,
			CreatedAt: now,
			UpdatedAt: now,
		})
		return nil
	}
	if err != nil {
		return fmt.Errorf("lookup mapping: %w", err)
	}

	setFields := bson.M{
		"status":        xo.Status,
		"totalNetEur":   netSales,
		"totalGrossEur": total,
		"userDef01":     soUserDefs[0],
		"userDef02":     soUserDefs[1],
		"userDef03":     soUserDefs[2],
		"userDef04":     soUserDefs[3],
		"userDef05":     soUserDefs[4],
		"userDef06":     soUserDefs[5],
		"userDef07":     soUserDefs[6],
		"userDef08":     soUserDefs[7],
		"userDef09":     soUserDefs[8],
		"userDef10":     soUserDefs[9],
		"updatedAt":     now,
	}
	if customerID != nil {
		setFields["customerId"] = customerID
	}
	if len(lineItems) > 0 {
		setFields["lineItems"] = lineItems
	}
	_, _ = e.db.SalesOrders().UpdateOne(ctx,
		bson.M{"_id": mapping.LocalID, "tenantId": tenantID},
		bson.M{"$set": setFields},
	)
	return nil
}

