// startLog marks any pre-existing "running" logs for the given entity+tenant
// as aborted, then inserts a fresh "running" log and returns it.
// This ensures stale "running" entries (e.g. from a previously cancelled sync)
// are always resolved before a new run begins.
func (e *Engine) startLog(ctx context.Context, tenantID primitive.ObjectID, entity string) models.XentralSyncLog {
	now := time.Now()
	writeCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	e.db.XentralSyncLogs().UpdateMany(writeCtx, //nolint
		bson.M{"tenantId": tenantID, "entity": entity, "status": "running"},
		bson.M{"$set": bson.M{
			"status":     "error",
			"errors":     []string{"Abgebrochen (neuer Sync gestartet)"},
			"finishedAt": now,
		}},
	)
	log := models.XentralSyncLog{
		ID:        primitive.NewObjectID(),
		TenantID:  tenantID,
		Entity:    entity,
		Status:    "running",
		StartedAt: now,
	}
	e.db.XentralSyncLogs().InsertOne(writeCtx, log) //nolint
	return log
}

func (e *Engine) failLog(ctx context.Context, log models.XentralSyncLog, errMsg string) models.XentralSyncLog {
	now := time.Now()
	log.Status = "error"
	log.Errors = []string{errMsg}
	log.FinishedAt = &now
	// Use a fresh context so the log update is never blocked by a cancelled request context.
	writeCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	e.db.XentralSyncLogs().UpdateOne(writeCtx, //nolint
		bson.M{"_id": log.ID},
		bson.M{"$set": bson.M{"status": log.Status, "errors": log.Errors, "finishedAt": log.FinishedAt}},
	)
	return log
}

func (e *Engine) finishLog(ctx context.Context, log models.XentralSyncLog) models.XentralSyncLog {
	now := time.Now()
	log.Status = "success"
	if len(log.Errors) > 0 {
		log.Status = "partial"
	}
	log.FinishedAt = &now
	// Use a fresh context so the log update is never blocked by a cancelled request context.
	writeCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	e.db.XentralSyncLogs().UpdateOne(writeCtx, //nolint
		bson.M{"_id": log.ID},
		bson.M{"$set": bson.M{
			"status":     log.Status,
			"created":    log.Created,
			"updated":    log.Updated,
			"skipped":    log.Skipped,
			"errors":     log.Errors,
			"finishedAt": log.FinishedAt,
		}},
	)
	_ = ctx // context was used for the sync work; log write uses its own context above
	return log
}

// Truncate is the exported version used by the handlers package.
func Truncate(s string, max int) string {
	if len(s) <= max {
		return s
	}
	return s[:max]
}

func truncate(s string, max int) string { return Truncate(s, max) }

// resolveTagNames extracts the Name field from XTag objects returned by Xentral.
// Empty names are dropped.
func resolveTagNames(tags []XTag) []string {
	if len(tags) == 0 {
		return nil
	}
	out := make([]string, 0, len(tags))
	for _, t := range tags {
		if t.Name != "" {
			out = append(out, t.Name)
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// resolveAttributes converts Xentral characteristics into ProductAttribute structs.
// Entries without a name are skipped. Value and Unit are truncated to model limits.
func resolveAttributes(chars []XCharacteristic) []models.ProductAttribute {
	if len(chars) == 0 {
		return nil
	}
	out := make([]models.ProductAttribute, 0, len(chars))
	for _, c := range chars {
		if c.Name == "" {
			continue
		}
		out = append(out, models.ProductAttribute{
			Key:   truncate(c.Name, 100),
			Value: truncate(c.Value, 500),
			Unit:  truncate(c.Unit, 30),
		})
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// resolveFreeFields converts XV2FreeField entries from the v2 products API into
// ProductFreeField model objects, skipping entries without a value.
// The name is taken from the non-null Name pointer; entries with null name are kept
// if they have a value (using empty string as name in that case).
func resolveFreeFields(fields []XV2FreeField) []models.ProductFreeField {
	if len(fields) == 0 {
		return nil
	}
	out := make([]models.ProductFreeField, 0, len(fields))
	for _, f := range fields {
		if f.Value == "" {
			continue
		}
		name := ""
		if f.Name != nil {
			name = *f.Name
		}
		out = append(out, models.ProductFreeField{
			ID:    f.ID,
			Name:  truncate(name, 255),
			Value: truncate(f.Value, 500),
		})
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// mapFreifelderToUserDefs maps Xentral freifeld1..10 directly to UserDef01..10 (1:1).
// Used for orders and sales orders (v1/v3 API still uses flat freifeld fields).
func mapFreifelderToUserDefs(freifelder map[string]string) [10]string {
	var result [10]string
	for i := range result {
		key := fmt.Sprintf("freifeld%d", i+1)
		if v, ok := freifelder[key]; ok {
			result[i] = truncate(v, 255)
		}
	}
	return result
}
