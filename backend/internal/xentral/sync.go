func (e *Engine) upsertOrder(ctx context.Context, tenantID primitive.ObjectID, xo XPurchaseOrder, client *Client) error {
	if xo.ID == "" {
		return nil
	}

	// Fetch line items via separate endpoint – the v3 list response does not include them.
	if items, err := client.ListPurchaseOrderLineItems(ctx, xo.ID); err == nil && len(items) > 0 {
		xo.LineItems = items
	}

	var mapping models.XentralMapping
	err := e.db.XentralMappings().FindOne(ctx, bson.M{
		"tenantId":  tenantID,
		"entity":    "order",
		"xentralId": xo.ID,
	}).Decode(&mapping)

	now := time.Now()

	// Resolve order date from Xentral. Try ISO date first, then datetime prefix.
	orderDate := now
	if d := xo.ResolvedDate(); d != "" {
		for _, layout := range []string{"2006-01-02T15:04:05Z", "2006-01-02T15:04:05", "2006-01-02"} {
			if t, parseErr := time.Parse(layout, d); parseErr == nil {
				orderDate = t
				break
			}
		}
	}

	// Resolve supplier via mapping (requires suppliers sync to have run first).
	// The v3 API stores the supplier as address.id; use ResolvedSupplierID() to handle both formats.
	supplierID := e.resolveSupplierID(ctx, tenantID, xo.ResolvedSupplierID())

	// Build order products from ALL line items.
	// ProductID is optional: items imported before the products sync runs still carry
	// XentralArticleID so they can be resolved on the next sync pass.
	var orderProducts []models.OrderProduct
	for _, item := range xo.LineItems {
		qty := int(item.Quantity)
		if qty < 1 {
			qty = 1
		}
		op := models.OrderProduct{
			XentralArticleID:     item.Article.ID,
			XentralArticleNumber: item.Article.ArticleNumber,
			Description:          item.Description,
			Quantity:             qty,
			UnitPriceUSD:         item.UnitPrice,
			TotalPriceUSD:        item.UnitPrice * float64(qty),
		}
		if pid := e.resolveProductID(ctx, tenantID, item.Article.ID); pid != nil {
			op.ProductID = pid
		}
		orderProducts = append(orderProducts, op)
	}

	currency := xo.ResolvedCurrency()
	orderNumber := xo.ResolvedOrderNumber()
	totalNet := xo.ResolvedTotalNet()
	orderUserDefs := mapFreifelderToUserDefs(xo.ResolvedFreifelder())

	if err == mongo.ErrNoDocuments {
		order := models.Order{
			ID:          primitive.NewObjectID(),
			TenantID:    tenantID,
			SupplierID:  supplierID,
			OrderNumber: orderNumber,
			OrderDate:   orderDate,
			Currency:    currency,
			OrderSumUSD: totalNet,
			Products:    orderProducts,
			UserDef01:   orderUserDefs[0],
			UserDef02:   orderUserDefs[1],
			UserDef03:   orderUserDefs[2],
			UserDef04:   orderUserDefs[3],
			UserDef05:   orderUserDefs[4],
			UserDef06:   orderUserDefs[5],
			UserDef07:   orderUserDefs[6],
			UserDef08:   orderUserDefs[7],
			UserDef09:   orderUserDefs[8],
			UserDef10:   orderUserDefs[9],
			CreatedAt:   now,
			UpdatedAt:   now,
		}
		if _, insertErr := e.db.Orders().InsertOne(ctx, order); insertErr != nil {
			return fmt.Errorf("insert order: %w", insertErr)
		}
		_, _ = e.db.XentralMappings().InsertOne(ctx, models.XentralMapping{
			ID:        primitive.NewObjectID(),
			TenantID:  tenantID,
			Entity:    "order",
			LocalID:   order.ID,
			XentralID: xo.ID,
			XentralNr: orderNumber,
			CreatedAt: now,
			UpdatedAt: now,
		})
		return nil
	}
	if err != nil {
		return fmt.Errorf("lookup mapping: %w", err)
	}

	setFields := bson.M{
		"orderSumUsd": totalNet,
		"currency":    currency,
		"orderDate":   orderDate,
		"userDef01":   orderUserDefs[0],
		"userDef02":   orderUserDefs[1],
		"userDef03":   orderUserDefs[2],
		"userDef04":   orderUserDefs[3],
		"userDef05":   orderUserDefs[4],
		"userDef06":   orderUserDefs[5],
		"userDef07":   orderUserDefs[6],
		"userDef08":   orderUserDefs[7],
		"userDef09":   orderUserDefs[8],
		"userDef10":   orderUserDefs[9],
		"updatedAt":   now,
	}
	if supplierID != nil {
		setFields["supplierId"] = supplierID
	}
	// Only overwrite line items when Xentral actually returned some.
	// If the list endpoint omits lineItems (e.g. large response truncation or API version
	// differences), we keep whatever we already have rather than wiping existing data.
	if len(orderProducts) > 0 {
		setFields["products"] = orderProducts
	}
	_, _ = e.db.Orders().UpdateOne(ctx,
		bson.M{"_id": mapping.LocalID, "tenantId": tenantID},
		bson.M{"$set": setFields},
	)
	return nil
}

