// Stocks per product (official /api/products/:id/stocks, v1-beta)
// -------------------------------------------------------------------

// SyncStocksPerProduct fetches stock levels using the official v1-beta endpoint
// GET /api/products/{id}/stocks and upserts one StockLevel record per warehouse
// per product. This is the recommended approach for the initial stock import.
//
// Prerequisites: warehouses must already be synced (SyncWarehouses) so that
// Xentral warehouse IDs can be resolved to local ObjectIDs.
func (e *Engine) SyncStocksPerProduct(ctx context.Context, tenantID primitive.ObjectID, client *Client) models.XentralSyncLog {
	log := e.startLog(ctx, tenantID, "stocks_per_product")

	// Collect all mapped products for this tenant.
	cursor, err := e.db.XentralMappings().Find(ctx, bson.M{"tenantId": tenantID, "entity": "product"})
	if err != nil {
		return e.failLog(ctx, log, "find product mappings: "+err.Error())
	}
	defer cursor.Close(ctx)

	for cursor.Next(ctx) {
		var mapping models.XentralMapping
		if err := cursor.Decode(&mapping); err != nil {
			log.Errors = append(log.Errors, "decode mapping: "+err.Error())
			log.Skipped++
			continue
		}

		summary, err := client.GetProductStockSummary(ctx, mapping.XentralID)
		if err != nil {
			log.Errors = append(log.Errors, mapping.XentralID+": "+err.Error())
			log.Skipped++
			continue
		}

		for _, wEntry := range summary.Warehouses {
			if err := e.upsertStockFromSummary(ctx, tenantID, mapping.LocalID, mapping.XentralID, wEntry); err != nil {
				log.Errors = append(log.Errors, mapping.XentralID+"#"+wEntry.ID+": "+err.Error())
				log.Skipped++
			} else {
				log.Updated++
			}
		}
	}
	if err := cursor.Err(); err != nil {
		log.Errors = append(log.Errors, "cursor: "+err.Error())
	}

	return e.finishLog(ctx, log)
}

// upsertStockFromSummary writes one StockLevel row for a product/warehouse pair
// from the per-product stock summary endpoint.
// Identity key: tenantId + xentralId (= "productXentralId#warehouseXentralId").
func (e *Engine) upsertStockFromSummary(
	ctx context.Context,
	tenantID primitive.ObjectID,
	productID primitive.ObjectID,
	xentralProductID string,
	wEntry XStockWarehouseEntry,
) error {
	// Resolve warehouse ObjectID (best-effort; falls back to no warehouseId).
	var warehouseID *primitive.ObjectID
	var wh struct {
		ID primitive.ObjectID `bson:"_id"`
	}
	if err := e.db.Warehouses().FindOne(ctx, bson.M{"tenantId": tenantID, "xentralId": wEntry.ID}).Decode(&wh); err == nil {
		warehouseID = &wh.ID
	}

	now := time.Now()
	xentralStockID := xentralProductID + "#" + wEntry.ID
	setFields := bson.M{
		"productId": productID,
		"quantity":  wEntry.Physical,
		"xentralId": xentralStockID,
		"updatedAt": now,
	}
	if warehouseID != nil {
		setFields["warehouseId"] = warehouseID
	}

	_, err := e.db.StockLevels().UpdateOne(ctx,
		bson.M{"tenantId": tenantID, "xentralId": xentralStockID},
		bson.M{"$set": setFields, "$setOnInsert": bson.M{"tenantId": tenantID, "createdAt": now}},
		options.Update().SetUpsert(true),
	)
	return err
}

func isDue(last *time.Time, now time.Time, interval time.Duration) bool {
	if last == nil {
		return true
	}
	return now.Sub(*last) >= interval
}

